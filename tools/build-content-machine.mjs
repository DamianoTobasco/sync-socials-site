#!/usr/bin/env node
// Builds the live template preview on the homepage from the app's own
// template engine, so the site plays exactly what the product renders.
//
//   node tools/build-content-machine.mjs <path to the app repo> [site dir]
//
// The app repo must have its node_modules installed: TypeScript (to strip the
// types) and Next's bundled terser (to minify) are borrowed from there, so the
// site itself stays dependency-free. Output:
//
//   content-machine-engine.js          the drawing code plus the sample specs
//   assets/fonts/content-machine/      the Latin font files the canvas uses
//
// Only what a preview needs is shipped. The agent-facing recipe for each
// template (story formula, writing rules) stays in the app.

import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import vm from "node:vm";

const [appArg, siteArg] = process.argv.slice(2);
if (!appArg) {
  console.error("usage: node tools/build-content-machine.mjs <path to the app repo> [site dir]");
  process.exit(1);
}
const appRoot = path.resolve(appArg);
const siteRoot = path.resolve(siteArg ?? ".");
const sourceRoot = path.join(appRoot, "src/lib/content-templates");
const appRequire = createRequire(path.join(appRoot, "package.json"));
const ts = appRequire("typescript");

// Everything the frame function needs, in dependency order.
const ENGINE_MODULES = [
  "engine/core",
  "engine/timeline",
  "engine/night-cam",
  "engine/blueprint",
  "engine/big-number",
  "engine/frame",
];

function transpile(id) {
  const source = readFileSync(path.join(sourceRoot, `${id}.ts`), "utf8");
  const { outputText } = ts.transpileModule(source, {
    fileName: `${id}.ts`,
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2019,
      removeComments: true,
    },
  });
  return outputText;
}

function resolveFrom(id, request) {
  return path.posix.normalize(path.posix.join(path.posix.dirname(id), request));
}

const modules = {};
for (const id of ENGINE_MODULES) {
  const code = transpile(id);
  // The engine imports the spec for its types only. A real import would pull
  // the whole validation library into the page, so fail loudly instead.
  for (const [, request] of code.matchAll(/require\("([^"]+)"\)/g)) {
    const target = resolveFrom(id, request);
    if (!ENGINE_MODULES.includes(target)) {
      throw new Error(`${id} imports ${request} at runtime; add it to ENGINE_MODULES or make the import type-only.`);
    }
  }
  modules[id] = code.replace(/require\("([^"]+)"\)/g, (_, request) => `require(${JSON.stringify(resolveFrom(id, request))})`);
}

// The catalogue is data. Evaluate it here and keep only what a visitor sees.
const catalogue = { exports: {} };
vm.runInNewContext(transpile("catalog"), { module: catalogue, exports: catalogue.exports, require: () => ({}) });
const templates = catalogue.exports.CONTENT_TEMPLATES.map((template) => ({
  id: template.id,
  name: template.name,
  tagline: template.tagline,
  bestFor: template.bestFor,
  accent: template.defaultAccent,
  sample: template.sample,
}));

let revision = "unknown";
try {
  revision = execFileSync("git", ["-C", appRoot, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
} catch {
  // Not a git checkout; the banner just says so.
}

const bundle = `(function () {
  "use strict";
  var modules = {
${ENGINE_MODULES.map((id) => `    ${JSON.stringify(id)}: function (module, exports, require) {\n${modules[id]}\n    }`).join(",\n")}
  };
  var cache = {};
  function load(id) {
    if (cache[id]) return cache[id].exports;
    var module = (cache[id] = { exports: {} });
    modules[id](module, module.exports, load);
    return module.exports;
  }
  var core = load("engine/core");
  var frame = load("engine/frame");
  window.SyncContentMachine = {
    width: core.FRAME_W,
    height: core.FRAME_H,
    templates: ${JSON.stringify(templates)},
    timeline: frame.templateTimeline,
    draw: frame.drawTemplateFrame
  };
})();
`;

const { minify } = appRequire("next/dist/compiled/terser");
const minified = await minify(bundle, { compress: true, mangle: true });
const banner = `/* Sync Socials content templates: preview engine.
   Generated by tools/build-content-machine.mjs from the app's
   src/lib/content-templates at ${revision}. Do not edit; rebuild instead. */\n`;
writeFileSync(path.join(siteRoot, "content-machine-engine.js"), banner + minified.code + "\n");

const FONTS = [
  "inter-latin-300-normal.woff2",
  "inter-latin-500-normal.woff2",
  "inter-latin-700-normal.woff2",
  "inter-latin-900-normal.woff2",
  "jetbrains-mono-latin-500-normal.woff2",
  "jetbrains-mono-latin-700-normal.woff2",
  "Inter-OFL.txt",
  "JetBrainsMono-OFL.txt",
];
const fontTarget = path.join(siteRoot, "assets/fonts/content-machine");
mkdirSync(fontTarget, { recursive: true });
for (const file of FONTS) {
  copyFileSync(path.join(appRoot, "public/fonts/content-templates", file), path.join(fontTarget, file));
}

console.log(
  `content-machine-engine.js: ${templates.length} templates (${templates.map((t) => t.id).join(", ")}), ` +
    `${(minified.code.length / 1024).toFixed(1)} KB, from app ${revision}`,
);
